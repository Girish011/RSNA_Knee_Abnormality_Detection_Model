#!/usr/bin/env python3
"""Kaggle benchmark of our inference leg on the scoring hardware (2 x T4, 4 vCPU): ours_leg (v1) vs ours_leg_v2.

    python scripts/build_leg_bench.py [--n 60] [--name leg-bench]
    kaggle kernels push -p outputs/kernels/leg-bench

The kernel points both legs at N train studies (same DICOM layout as the hidden test) and prints: v1 and v2 wall
time with the same five members, their output agreement, v2 with all fifteen own models, and v2 with the mirror
pass. Nothing is submitted; it answers how many models fit in the notebook's time limit.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
LEG = REPO / "outputs" / "kernels" / "_ours_leg"
USER = "girishbose"
FIVE = ["r2-c224hvy40-f0b:r2c224hvy400", "r2-c224hvy40-f1:r2c224hvy401", "r2-effv2s336-f0:r2effv2s3360",
        "r2-effv2s336-f1:r2effv2s3361", "r2-cnxs336-f0:r2cnxs3360"]
FIFTEEN = (["r2-c224hvy40-f0b:r2c224hvy400"] + [f"r2-c224hvy40-f{k}:r2c224hvy40{k}" for k in range(1, 5)]
           + [f"r2-effv2s336-f{k}:r2effv2s336{k}" for k in range(5)] + [f"r2-cnxs336-f{k}:r2cnxs336{k}" for k in range(5)])

BENCH = '''#!/usr/bin/env python3
"""Leg benchmark (generated by scripts/build_leg_bench.py). Internet OFF. Nothing is submitted."""
import json, os, subprocess, sys, time
import numpy as np
import pandas as pd

N = __N__
V1_SRC = __V1__
V2_SRC = __V2__
FIVE = __FIVE__
FIFTEEN = __FIFTEEN__
LAB = ["ACL", "MCL", "Medial Meniscus", "Lateral Meniscus", "Medial OA", "Lateral OA", "PF OA", "Effusion",
       "Synovitis", "Baker's", "Contusion", "Fracture"]
W = "/kaggle/working"

root = None
for d, _, f in os.walk("/kaggle/input"):
    if "train_series.csv" in f and os.path.isdir(d + "/train_series"):
        root = d
        break
assert root, "competition train data not found"
ser = pd.read_csv(root + "/train_series.csv", dtype={"StudyInstanceUID": str, "SeriesInstanceUID": str})
ids = sorted(ser["StudyInstanceUID"].unique())
ids = [ids[i] for i in np.random.default_rng(20261005).permutation(len(ids))[:N]]
fake = W + "/bench_root"
os.makedirs(fake, exist_ok=True)
pd.DataFrame({"StudyInstanceUID": ids}).to_csv(fake + "/test.csv", index=False)
ser[ser["StudyInstanceUID"].isin(ids)].to_csv(fake + "/test_series.csv", index=False)
if not os.path.exists(fake + "/test_series"):
    os.symlink(root + "/train_series", fake + "/test_series")
print(f"bench on {len(ids)} train studies | cpu {os.cpu_count()}", flush=True)
subprocess.call(["nvidia-smi", "--query-gpu=name,memory.total", "--format=csv"])

old = "    ROOT = find_test_root()\\n"
assert V1_SRC.count(old) == 1
open(W + "/_leg_v1.py", "w").write(V1_SRC.replace(old, '    ROOT = os.environ.get("OURS_ROOT") or find_test_root()\\n'))
open(W + "/_leg_v2.py", "w").write(V2_SRC)


def run(tag, leg, members, **env):
    out = f"{W}/_{tag}.csv"
    e = dict(os.environ, OURS_MEMBERS=json.dumps(members), OURS_OUT=out, OURS_ROOT=fake, **{k: str(v) for k, v in env.items()})
    t = time.time()
    rc = subprocess.call([sys.executable, f"{W}/_leg_{leg}.py"], env=e)
    dt = time.time() - t
    print(f"[bench] {tag}: rc {rc} | {dt:.0f} s total = {dt / len(ids):.2f} s/study incl. model load | "
          f"x1322 studies = {dt / len(ids) * 1322 / 60:.0f} min", flush=True)
    return out


def agree(a, b, what):
    A, B = pd.read_csv(a), pd.read_csv(b)
    assert A["StudyInstanceUID"].tolist() == B["StudyInstanceUID"].tolist()
    d = np.abs(A[LAB].to_numpy() - B[LAB].to_numpy())
    rho = [A[c].corr(B[c], method="spearman") for c in LAB]
    print(f"[bench] {what}: max |diff| {d.max():.4f} mean {d.mean():.5f} | spearman min {min(rho):.4f} mean {np.mean(rho):.4f}", flush=True)


a = run("v1_5", "v1", FIVE)
b = run("v2_5", "v2", FIVE)
agree(a, b, "v1 vs v2, five members, final rank mean")
for j in range(len(FIVE)):
    agree(a[:-4] + f"_m{j}.csv", b[:-4] + f"_m{j}.csv", f"  member {j} ({FIVE[j]})")
c = run("v2_15", "v2", FIFTEEN)
d = run("v2_15_flip", "v2", FIFTEEN, OURS_FLIP=1)
agree(c, d, "v2 fifteen members: plain vs mirror second pass")
e = run("v2_15_1gpu", "v2", FIFTEEN, OURS_GPUS=1)
agree(c, e, "v2 fifteen members: two GPUs vs one")
print("[bench] done", flush=True)
'''


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=60)
    ap.add_argument("--name", default="leg-bench")
    a = ap.parse_args()
    files = lambda specs: [f"raptor_ft_{s.split(':')[1]}.pt" for s in specs]
    src = (BENCH.replace("__N__", str(a.n)).replace("__V1__", repr((LEG / "ours_leg.py").read_text()))
           .replace("__V2__", repr((LEG / "ours_leg_v2.py").read_text()))
           .replace("__FIVE__", repr(files(FIVE))).replace("__FIFTEEN__", repr(files(FIFTEEN))))
    compile(src, "bench", "exec")
    d = REPO / "outputs" / "kernels" / a.name
    d.mkdir(parents=True, exist_ok=True)
    code = a.name.replace("-", "_") + ".py"
    (d / code).write_text(src)
    meta = json.loads((REPO / "outputs/kernels/probe-r1-c224x5/kernel-metadata.json").read_text())
    meta.update(id=f"{USER}/{a.name}", title=a.name, code_file=code,
                dataset_sources=[f"{USER}/rsna-knee-rp-{s.split(':')[0]}-out" for s in FIFTEEN])
    (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
    print(f"wrote {d} | {a.n} studies | push: kaggle kernels push -p {d}")


if __name__ == "__main__":
    main()
