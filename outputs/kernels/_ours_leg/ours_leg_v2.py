def build_backbone(arch, pretrained=False):
    hybrid = arch.startswith(("maxvit", "maxxvit", "coatnet", "coat_", "convnext"))
    is_vit = (not hybrid) and any(k in arch for k in ("vit", "deit", "dinov2", "eva", "beit"))
    kw = dict(pretrained=pretrained, num_classes=0, in_chans=3)
    if is_vit:
        kw.update(global_pool="token", dynamic_img_size=True)
    else:
        kw.update(global_pool="avg")
    return timm.create_model(arch, **kw)


class RaptorClassifier(nn.Module):
    def __init__(self, backbone, F_dim=768, n=12, drop=0.2):
        super().__init__()
        self.backbone = backbone
        self.norm = nn.LayerNorm(F_dim)
        self.att = nn.Sequential(nn.Linear(F_dim, 256), nn.Tanh(), nn.Dropout(drop),
                                 nn.Linear(256, n))
        self.clsW = nn.Parameter(torch.zeros(n, F_dim))
        self.clsb = nn.Parameter(torch.zeros(n))
        nn.init.trunc_normal_(self.clsW, std=0.02)
        self.n = n

    def encode(self, x):
        B, K = x.shape[:2]
        f = self.backbone(x.flatten(0, 1))
        return f.view(B, K, -1)

    def head(self, feats):
        h = self.norm(feats)
        a = torch.softmax(self.att(h), dim=1)
        pooled = torch.einsum("bkn,bkf->bnf", a, h)
        return (pooled * self.clsW).sum(-1) + self.clsb

    def forward(self, x, pos=None):
        return self.head(self.encode(x))


def _fourier(rel):
    f = rel[..., None] * (math.pi * (2.0 ** torch.arange(6, device=rel.device, dtype=rel.dtype)))
    return torch.cat([torch.sin(f), torch.cos(f)], -1)


class SeqClassifier(nn.Module):
    """train_knee.SeqClassifier (slot-aware head): same modules, same forward."""
    def __init__(self, backbone, F_dim=384, n=12, drop=0.2, use_tr=True, use_sp=False, D=384, layers=2, heads=6):
        super().__init__()
        self.backbone = backbone
        self.norm = nn.LayerNorm(F_dim)
        self.att = nn.Sequential(nn.Linear(F_dim, 256), nn.Tanh(), nn.Dropout(drop),
                                 nn.Linear(256, n))
        self.clsW = nn.Parameter(torch.zeros(n, F_dim))
        self.clsb = nn.Parameter(torch.zeros(n))
        self.n, self.use_tr, self.use_sp = n, bool(use_tr), bool(use_sp)
        self.blk_att = nn.Embedding(len(BLOCKS), F_dim)
        self.pos_att = nn.Linear(12, F_dim)
        if self.use_tr:
            self.proj_in = nn.Linear(F_dim, D)
            self.blk_tr = nn.Embedding(len(BLOCKS), D)
            self.pos_tr = nn.Linear(12, D)
            layer = nn.TransformerEncoderLayer(D, heads, 2 * D, dropout=0.1, batch_first=True, norm_first=True)
            self.tr = nn.TransformerEncoder(layer, layers, enable_nested_tensor=False)
            self.proj_out = nn.Linear(D, F_dim)
            self.gamma = nn.Parameter(torch.zeros(1))
        if self.use_sp:
            self.sp_norm = nn.LayerNorm(F_dim)
            self.sp = nn.Linear(F_dim, n)

    def forward(self, x, pos=None):
        B, K = x.shape[:2]
        if self.use_sp:
            fm = self.backbone.forward_features(x.flatten(0, 1))
            t = fm.flatten(2).transpose(1, 2)
            s = torch.softmax(self.sp(self.sp_norm(t)).float(), dim=1).to(t.dtype)
            g = torch.einsum("thn,thc->tnc", s, t)
            f = self.backbone.forward_head(g.reshape(-1, g.shape[-1], 1, 1)).view(B, K, self.n, -1)
        else:
            f = self.backbone(x.flatten(0, 1)).view(B, K, 1, -1)
        e_att = 0.0
        if pos is not None:
            blk, ff = pos[..., 0].long(), _fourier(pos[..., 1].float())
            e_att = (self.blk_att(blk) + self.pos_att(ff))[:, :, None, :]
            if self.use_tr:
                z = self.proj_in(self.norm(f.mean(2))) + self.blk_tr(blk) + self.pos_tr(ff)
                f = f + self.gamma * self.proj_out(self.tr(z))[:, :, None, :]
        h = self.norm(f)
        a = self.att(h + e_att)
        a = torch.diagonal(a, dim1=2, dim2=3) if self.use_sp else a[:, :, 0]
        a = torch.softmax(a.float(), dim=1).to(h.dtype)
        pooled = torch.einsum("bkn,bknf->bnf", a, h.expand(-1, -1, self.n, -1))
        return (pooled * self.clsW).sum(-1) + self.clsb


def load_model(pt_path, device):
    """-> (model, cfg); cfg = (res, sample, k_eval, canon) = the windows this member was trained and evaluated on
    (canon: left knees are shown mirrored, train_knee --canon)."""
    ck = torch.load(pt_path, map_location="cpu", weights_only=False)
    arch = ck.get("arch", ARCH_DEFAULT)
    res = int(ck.get("res", RES_DEFAULT))
    head = ck.get("head", "mil")
    bb = build_backbone(arch, pretrained=False)
    if head == "mil":
        model = RaptorClassifier(bb, F_dim=bb.num_features)
    else:
        model = SeqClassifier(bb, F_dim=bb.num_features, use_tr=head in ("seq", "seqtok"), use_sp=head in ("tok", "seqtok"))
    model.load_state_dict(ck["model"], strict=True)
    model.eval().to(device)
    cfg = (res, ck.get("sample", "rand"), int(os.environ.get("OURS_K_EVAL") or ck.get("k_eval", K_EVAL)), bool(ck.get("canon", False)))
    del ck
    gc.collect()
    return model, cfg


def _eval_centers(mask, D, k, phase=0.0):
    valid = np.where(mask > 0)[0]
    if len(valid) < 3:
        valid = np.arange(min(3, D))
    lo, hi = int(valid.min()), int(valid.max())
    cs = [c for c in range(lo + 1, hi) if c - 1 >= lo and c + 1 <= hi]
    if not cs:
        cs = [max(1, min((lo + hi) // 2, D - 2))]
    frac = (np.linspace(0.0, 1.0, k) + float(phase)) % 1.0
    idx = np.round(frac * (len(cs) - 1)).astype(int)
    return [cs[i] for i in idx]


def _alloc(sizes, count):
    tot = float(sum(sizes)) or 1.0
    raw = [count * z / tot for z in sizes]
    n = [int(r) for r in raw]
    for i in sorted(range(len(sizes)), key=lambda i: raw[i] - n[i], reverse=True)[:count - sum(n)]:
        n[i] += 1
    for i in range(len(n)):
        if n[i] == 0 and max(n) > 1:
            n[n.index(max(n))] -= 1; n[i] = 1
    return n


def _eval_centers_strat(mask, k, phase=0.0):
    """train_knee.StudyWindows._centers_strat at eval: ordered windows from every filled series block."""
    spans = []
    for s, e in BLOCKS:
        v = np.where(mask[s:e] > 0)[0]
        if len(v) == 0:
            continue
        lo, hi = s + int(v.min()) + 1, s + int(v.max()) - 1
        if hi < lo:
            lo = hi = max(s + 1, min(s + int(v[len(v) // 2]), e - 2))
        spans.append((lo, hi))
    if not spans:
        return [1] * k
    cs = []
    for (lo, hi), n in zip(spans, _alloc([hi - lo + 1 for lo, hi in spans], k)):
        for j in range(n):
            u = ((j + 0.5 + float(phase)) / n) % 1.0
            cs.append(lo + int(round(u * (hi - lo))))
    return cs


def _slot_pos(cs, D):
    out = np.zeros((len(cs), 2), np.float32)
    for i, c in enumerate(cs):
        if D != 80:
            out[i] = (0.0, c / max(D - 1, 1)); continue
        for b, (s, e) in enumerate(BLOCKS):
            if s <= c < e:
                out[i] = (b, (c - s) / (e - s - 1.0)); break
    return torch.from_numpy(out)


def eval_windows(vol, mask, k, res, phase=0.0, norm=NORM, flip=False, sample="rand"):
    return eval_windows_pos(vol, mask, k, res, phase=phase, norm=norm, flip=flip, sample=sample)[0]


def eval_windows_pos(vol, mask, k, res, phase=0.0, norm=NORM, flip=False, sample="rand"):
    """-> (x (K,3,res,res), pos (K,2) = series block and position inside it of every window)."""
    D = vol.shape[0]
    cs = _eval_centers_strat(mask, k, phase=phase) if sample == "strat" and D == 80 else _eval_centers(mask, D, k, phase=phase)
    pos = _slot_pos([max(1, min(c, D - 2)) for c in cs], D)
    wins = np.empty((len(cs), 3, res, res), np.float32)
    for j, c in enumerate(cs):
        c = max(1, min(c, D - 2))
        tri = np.stack([vol[c - 1], vol[c], vol[c + 1]], 0).astype(np.float32) / 255.0
        t = torch.from_numpy(tri)
        if t.shape[-1] != res or t.shape[-2] != res:
            t = F.interpolate(t[None], size=(res, res), mode="bilinear", align_corners=False)[0]
        wins[j] = t.numpy()
    x = torch.from_numpy(wins)
    if flip:   # train_knee._mirror: sagittal windows reverse their slice (= channel) order, the others flip in-plane
        for j, c in enumerate(cs):
            x[j] = x[j].flip(0) if c < SAG_SLOTS else x[j].flip(-1)
        sag = pos[:, 0] < 2
        pos[sag, 1] = 1.0 - pos[sag, 1]
    if norm == "imagenet":
        x = (x - _MEAN) / _STD
    return x, pos


@torch.no_grad()
def infer_probs(model, x, device, pos=None):
    """x: (P,K,3,res,res) already on `device`, one row per eval pass -> (12,) mean probability over the passes."""
    if str(device).startswith("cuda"):
        try:
            with torch.autocast("cuda", dtype=torch.float16):
                o = torch.sigmoid(model(x, pos).float())
            return o.mean(0).cpu().numpy()
        except RuntimeError:
            torch.cuda.empty_cache()
            return torch.sigmoid(model(x, pos).float()).mean(0).cpu().numpy()
    return torch.sigmoid(model(x, pos).float()).mean(0).cpu().numpy()


def _make_reader():
    import cv2
    import pydicom
    from pydicom.pixel_data_handlers.util import apply_modality_lut

    def order_and_meta(sdir, geo=None):
        """geo (optional dict) receives the series' left-right position: 'cx' = x of the stack centre in patient
        coordinates (mm, + = patient left; same formula as outputs/kernels/geom-dump) and 'tag' = Laterality."""
        fs = glob.glob(sdir + "/*.dcm")
        recs, ps_list = [], []
        xs, half, tag = [], None, ""
        for f in fs:
            try:
                h = pydicom.dcmread(f, stop_before_pixels=True)
                iop = getattr(h, "ImageOrientationPatient", None)
                ipp = getattr(h, "ImagePositionPatient", None)
                if iop is not None and ipp is not None and len(iop) == 6:
                    r = np.array(iop[:3], float)
                    c = np.array(iop[3:], float)
                    n = np.cross(r, c)
                    pos = float(np.dot(np.array(ipp, float), n))
                else:
                    pos = float(getattr(h, "InstanceNumber", 0) or 0)
                ps = getattr(h, "PixelSpacing", None)
                if geo is not None:
                    try:
                        if iop is not None and ipp is not None and len(iop) == 6 and len(ipp) == 3:
                            xs.append(float(ipp[0]))
                            if half is None:
                                half = (0.5 * int(getattr(h, "Columns", 0) or 0) * (float(ps[1]) if ps is not None else 0.5) * float(iop[0])
                                        + 0.5 * int(getattr(h, "Rows", 0) or 0) * (float(ps[0]) if ps is not None else 0.5) * float(iop[3]))
                        if not tag:
                            tag = (str(getattr(h, "Laterality", "") or "").strip() or str(getattr(h, "ImageLaterality", "") or "").strip())[:1].upper()
                    except Exception:
                        pass
                ps = float(ps[0]) if ps is not None else 0.5
                ps_list.append(ps)
                recs.append((pos, f, ps))
            except Exception:
                recs.append((0.0, f, 0.5))
        recs.sort(key=lambda x: x[0])
        med_ps = float(np.median(ps_list)) if ps_list else 0.5
        if geo is not None:
            geo["cx"] = (float(np.mean(xs)) + half) if xs and half is not None else None
            geo["tag"] = tag
        return [(f, ps) for _, f, ps in recs], med_ps

    def read_px(f):
        d = pydicom.dcmread(f)
        a = apply_modality_lut(d.pixel_array, d).astype(np.float32)
        if str(getattr(d, "PhotometricInterpretation", "")) == "MONOCHROME1":
            a = a.max() - a
        return a

    def mm_crop_resize(a, ps):
        h, w = a.shape
        cpx = int(round(CROP_MM / max(ps, 1e-3)))
        cpx = min(cpx, min(h, w))
        y0 = (h - cpx) // 2
        x0 = (w - cpx) // 2
        a = a[y0:y0 + cpx, x0:x0 + cpx]
        return cv2.resize(a, (IMG, IMG), interpolation=cv2.INTER_AREA)

    return order_and_meta, read_px, mm_crop_resize


def _pick_series_for_slot(rows, plane, fluid, used):
    cands = [r for r in rows if r["Anatomical_Plane"] == plane and r["SeriesInstanceUID"] not in used]
    if fluid in (0, 1):
        pref = [r for r in cands if int(r.get("Fluid_Sensitive", 0) or 0) == fluid]
        if pref:
            return pref[0]
    return cands[0] if cands else None


def knee_is_left(cxs, tags):
    """Side of the knee as the images show it (rule of agent/protocol/knee_sides.json): the sign of the stack centre's
    x; within 5 mm of the midline the Laterality tag decides if there is one."""
    cx = float(np.median(cxs)) if cxs else 0.0
    tag = next((t for t in tags if t in ("L", "R")), None)
    if abs(cx) > 5 or tag is None:
        return cx > 0
    return tag == "L"


def build_study(sid, ser_records, tsdir, reader, with_side=False):
    order_and_meta, read_px, mm_crop_resize = reader
    rows = ser_records.get(sid, [])
    vol = np.zeros((MAXS, IMG, IMG), np.uint8)
    idx = 0
    used = set()
    cxs, tags = [], []
    for plane, fluid, k in SLOTS:
        r = _pick_series_for_slot(rows, plane, fluid, used)
        if r is None:
            idx += k
            continue
        used.add(r["SeriesInstanceUID"])
        geo = {}
        files, med_ps = order_and_meta(f"{tsdir}/{sid}/{r['SeriesInstanceUID']}", geo)
        if geo.get("cx") is not None:
            cxs.append(geo["cx"])
        tags.append(geo.get("tag", ""))
        if not files:
            idx += k
            continue
        n = len(files)
        lo, hi = int(n * SPAN_LO), int(n * SPAN_HI) - 1
        hi = max(hi, lo)
        picks = np.linspace(lo, hi, k).round().astype(int) if n > 1 else [0] * k
        arrs, pss = [], []
        for p in picks:
            fp, ps = files[min(int(p), n - 1)]
            try:
                arrs.append(read_px(fp))
                pss.append(ps)
            except Exception:
                arrs.append(None)
                pss.append(med_ps)
        valid = [a for a in arrs if a is not None]
        if valid:
            allpx = np.concatenate([a.ravel() for a in valid])
            loq, hiq = np.percentile(allpx, [2.0, 98.0])
        else:
            loq, hiq = 0.0, 1.0
        for a, ps in zip(arrs, pss):
            if idx >= MAXS:
                break
            if a is None:
                idx += 1
                continue
            aw = np.clip((a - loq) / (hiq - loq + 1e-6), 0, 1)
            aw = mm_crop_resize(aw, ps if ps > 0 else med_ps)
            vol[idx] = (aw * 255).astype(np.uint8)
            idx += 1
        if idx >= MAXS:
            break
    mask = (vol.reshape(MAXS, -1).sum(1) > 0).astype(np.uint8)
    if with_side:
        return vol, mask, knee_is_left(cxs, tags)
    return vol, mask


