class _Studies(torch.utils.data.Dataset):
    """One item = one built study (80 x 336 x 336 uint8 + slot mask). Runs inside DataLoader workers."""

    def __init__(self, ids, ser, tsdir):
        self.ids, self.ser, self.tsdir, self._reader = ids, ser, tsdir, None

    def __len__(self):
        return len(self.ids)

    def __getitem__(self, i):
        t = time.time()
        try:
            if self._reader is None:
                import cv2
                cv2.setNumThreads(1)
                self._reader = _make_reader()
            vol, mask, left = build_study(self.ids[i], self.ser, self.tsdir, self._reader, with_side=True)
            return i, vol, mask, time.time() - t, "", left
        except Exception as e:
            return i, None, None, time.time() - t, f"{type(e).__name__}: {e}", False


